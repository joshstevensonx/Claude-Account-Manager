#!/usr/bin/env python3
"""
Claude Account Manager — a local dashboard for running several Claude
accounts side by side on macOS.

Each profile gets its own isolated data folders:
  ~/.claude-system/profiles/<id>/desktop   -> Claude desktop app (--user-data-dir)
  ~/.claude-system/profiles/<id>/cli       -> Claude Code (CLAUDE_CONFIG_DIR)
  ~/.claude-system/profiles/<id>/browser   -> Chrome window for claude.ai (--user-data-dir)

Standard library only (works with the macOS system python3, 3.9+).
Run:  python3 manager.py         (opens http://127.0.0.1:7788)
"""
