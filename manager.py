import os
import re
import secrets
import shlex
import shutil
import signal
import subprocess
import sys
import threading
import time
import webbrowser
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
from pathlib import Path
from urllib.parse import urlparse, parse_qs

sys.path.insert(0, str(Path(__file__).resolve().parent))
import monitor  # noqa: E402

HERE = Path(__file__).resolve().parent
HOME = Path(os.environ.get("CLAUDE_SYSTEM_HOME", Path.home() / ".claude-system"))
PROFILES_DIR = HOME / "profiles"
REGISTRY = HOME / "profiles.json"
SETTINGS = HOME / "settings.json"
ALIASES = HOME / "aliases.zsh"
LOG = HOME / "manager.log"
DRY_RUN = os.environ.get("CLAUDE_SYSTEM_DRY_RUN") == "1"  # log commands instead of running them
PORT = int(os.environ.get("CLAUDE_SYSTEM_PORT", "7788"))
TOKEN = secrets.token_urlsafe(24)
LOCK = threading.Lock()

DEFAULT_SETTINGS = {
    "terminal": "Terminal",          # "Terminal" or "iTerm"
    "desktop_app": "Claude",
    "browser_app": "Google Chrome",
    "claude_cli": "claude",
    "notify_done": True,             # a session finished its turn / a task finished
    "notify_approval": True,         # a session seems to be waiting for tool approval
    "notify_limits": True,           # an account crossed a plan-usage threshold
    "alert_thresholds": [80, 95],
}

COLORS = ["#d97757", "#6a9bcc", "#788c5d", "#b07cc6", "#c9a227", "#4fa3a5", "#c75b7a", "#7f8c9b"]


# ---------------------------------------------------------------- storage
def log(msg):
    HOME.mkdir(parents=True, exist_ok=True)
    with open(LOG, "a") as f:
        f.write(time.strftime("%Y-%m-%d %H:%M:%S ") + msg + "\n")


def load_json(path, default):
    try:
        with open(path) as f:
            return json.load(f)
    except (OSError, ValueError):
        return default


def save_json(path, data):
    HOME.mkdir(parents=True, exist_ok=True)
    tmp = path.with_suffix(".tmp")
    with open(tmp, "w") as f:
        json.dump(data, f, indent=2)
    os.replace(tmp, path)


def settings():
    s = dict(DEFAULT_SETTINGS)
    s.update(load_json(SETTINGS, {}))
    return s


def registry():
    data = load_json(REGISTRY, None)
    if data is None:
        data = {"profiles": [{
            "id": "default", "name": "Default", "note": "Your normal Claude install",
            "color": COLORS[0], "workdir": str(Path.home()), "builtin": True,
            "created": time.time(), "last_used": None,
        }]}
        save_json(REGISTRY, data)
    return data


def find(pid):
    for p in registry()["profiles"]:
        if p["id"] == pid:
            return p
    return None


def slug(name):
    s = re.sub(r"[^a-z0-9]+", "-", name.lower()).strip("-")[:32]
    return s or "profile"


def paths(p):
    """Data folders for a profile. The built-in default uses the normal locations."""
    if p.get("builtin"):
        return {
            "desktop": Path.home() / "Library/Application Support/Claude",
            "cli": Path.home() / ".claude",
            "cli_json": Path.home() / ".claude.json",
            "browser": None,
        }
    base = PROFILES_DIR / p["id"]
    return {
        "desktop": base / "desktop",
        "cli": base / "cli",
        "cli_json": base / "cli" / ".claude.json",
        "browser": base / "browser",
    }


def write_aliases():
    lines = ["# Generated by Claude Account Manager — `source` this from ~/.zshrc", ""]
    for p in registry()["profiles"]:
        if p.get("builtin"):
            continue
        cfg = str(paths(p)["cli"]).replace('"', '\\"').replace("'", "")
        lines.append("alias claude-%s='CLAUDE_CONFIG_DIR=\"%s\" claude'" % (p["id"], cfg))
    HOME.mkdir(parents=True, exist_ok=True)
    ALIASES.write_text("\n".join(lines) + "\n")


# ---------------------------------------------------------------- processes
def ps_lines():
    """Return [(pid, full command incl. environment)]. macOS `ps e` appends env vars."""
    try:
        out = subprocess.run(["ps", "-axeww", "-o", "pid=,command="],
                             capture_output=True, text=True, timeout=5).stdout
    except Exception:
        return []
    rows = []
    for line in out.splitlines():
        line = line.strip()
        if not line:
            continue
        pid, _, cmd = line.partition(" ")
        if pid.isdigit():
            rows.append((int(pid), cmd))
    return rows


def classify(rows, s):
    """Map processes onto profiles: {profile_id: {desktop:[pids], browser:[pids], cli:[pids]}}"""
    profs = registry()["profiles"]
    result = {p["id"]: {"desktop": [], "browser": [], "cli": []} for p in profs}
    by_desktop, by_browser, by_cli = {}, {}, {}
    for p in profs:
        pa = paths(p)
        if not p.get("builtin"):
            by_desktop[str(pa["desktop"])] = p["id"]
            by_browser[str(pa["browser"])] = p["id"]
            by_cli[str(pa["cli"])] = p["id"]
    desk_bin = "%s.app/Contents/MacOS/" % s["desktop_app"]
    brow_bin = "%s.app/Contents/MacOS/" % s["browser_app"]
    udd = re.compile(r"--user-data-dir=(\S+)")
    cfgre = re.compile(r"(?:^|\s)CLAUDE_CONFIG_DIR=(\S+)")
    for pid, cmd in rows:
        if desk_bin in cmd and "Helper" not in cmd.split(" --")[0]:
            m = udd.search(cmd)
            if m:
                owner = by_desktop.get(m.group(1).rstrip("/"))
                if owner:
                    result[owner]["desktop"].append(pid)
            elif "default" in result:
                result["default"]["desktop"].append(pid)
        elif brow_bin in cmd and "Helper" not in cmd.split(" --")[0]:
            m = udd.search(cmd)
            owner = m and by_browser.get(m.group(1).rstrip("/"))
            if owner:
                result[owner]["browser"].append(pid)
        else:
            argv0 = cmd.split(" ", 1)[0]
            is_cli = os.path.basename(argv0) == "claude" or "@anthropic-ai/claude-code" in cmd
            if not is_cli:
                continue
            m = cfgre.search(cmd)
            if m:
                owner = by_cli.get(m.group(1).rstrip("/"))
                if owner:
                    result[owner]["cli"].append(pid)
            elif "default" in result:
                result["default"]["cli"].append(pid)
    return result


def cli_account(p):
    """Email / org of the account Claude Code is signed in with, if any."""
    data = load_json(paths(p)["cli_json"], {})
    acct = data.get("oauthAccount") or {}
    return {
        "email": acct.get("emailAddress"),
        "org": acct.get("organizationName"),
    }


def folder_size(path):
    if not path or not Path(path).exists():
        return 0
    total = 0
    for root, _, files in os.walk(path):
        for f in files:
            try:
                total += os.lstat(os.path.join(root, f)).st_size
            except OSError:
                pass
    return total


# ---------------------------------------------------------------- launching
def resolve_cli():
    """Full path to Claude Code, so it's found even when PATH is minimal."""
    name = os.path.expanduser(settings()["claude_cli"])
    if os.sep in name:
        return name
    found = shutil.which(name)
    if found:
        return found
    for cand in ("~/.local/bin/claude", "~/.claude/local/claude", "/opt/homebrew/bin/claude",
                 "/usr/local/bin/claude", "~/.npm-global/bin/claude"):
        c = os.path.expanduser(cand)
        if os.path.exists(c):
            return c
    return name


def run(cmd):
    log(("DRY " if DRY_RUN else "RUN ") + " ".join(shlex.quote(c) for c in cmd))
    if DRY_RUN:
        return
    subprocess.Popen(cmd, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL, start_new_session=True)


def osa_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def touch(p):
    with LOCK:
        data = registry()
        for q in data["profiles"]:
            if q["id"] == p["id"]:
                q["last_used"] = time.time()
        save_json(REGISTRY, data)


def launch(p, kind, workdir=None, extra_args=None):
    s = settings()
    pa = paths(p)
    if kind == "desktop":
        if p.get("builtin"):
            run(["open", "-a", s["desktop_app"]])
        else:
            pa["desktop"].mkdir(parents=True, exist_ok=True)
            run(["open", "-n", "-a", s["desktop_app"], "--args", "--user-data-dir=%s" % pa["desktop"]])
    elif kind == "browser":
        if p.get("builtin"):
            run(["open", "https://claude.ai"])
        else:
            pa["browser"].mkdir(parents=True, exist_ok=True)
            run(["open", "-n", "-a", s["browser_app"], "--args",
                 "--user-data-dir=%s" % pa["browser"], "--no-first-run",
                 "--no-default-browser-check", "https://claude.ai"])
    elif kind == "cli":
        wd = os.path.expanduser(workdir or p.get("workdir") or "~")
        if not os.path.isdir(wd):
            wd = str(Path.home())
        title = "Claude · %s" % p["name"]
        parts = ["cd %s" % shlex.quote(wd)]
        if not p.get("builtin"):
            pa["cli"].mkdir(parents=True, exist_ok=True)
            parts.append("export CLAUDE_CONFIG_DIR=%s" % shlex.quote(str(pa["cli"])))
        parts.append("printf '\\033]0;%s\\007'" % title.replace("'", ""))
        parts.append("clear")
        parts.append(" ".join([shlex.quote(resolve_cli())] + [shlex.quote(a) for a in (extra_args or [])]))
        shell = " && ".join(parts)
        if s["terminal"].lower().startswith("iterm"):
            script = ('tell application "iTerm"\n activate\n set w to (create window with default profile)\n'
                      ' tell current session of w to write text %s\nend tell') % osa_str(shell)
        else:
            script = 'tell application "Terminal"\n activate\n do script %s\nend tell' % osa_str(shell)
        run(["osascript", "-e", script])
    else:
        raise ValueError("unknown kind")
    touch(p)


def stop(p, kind):
    procs = classify(ps_lines(), settings())[p["id"]][kind]
    for pid in procs:
        log(("DRY " if DRY_RUN else "") + "kill %d (%s/%s)" % (pid, p["id"], kind))
        if not DRY_RUN:
            try:
                os.kill(pid, signal.SIGTERM)
            except OSError:
                pass
    return len(procs)


# ---------------------------------------------------------------- API
def state():
    s = settings()
    procs = classify(ps_lines(), s)
    snap = WATCH.snapshot()
    out = []
    for p in registry()["profiles"]:
        pa = paths(p)
        item = dict(p)
        mine = [x for x in snap["sessions"] if x["profile"] == p["id"]]
        item["sessions"] = {k: sum(1 for x in mine if x["status"] == k) for k in ("working", "needs_you", "waiting")}
        plan = snap["plan"].get(p["id"]) or {}
        item["plan"] = {"available": plan.get("available", False), "binding": plan.get("binding"),
                        "stale": plan.get("stale"), "observed": plan.get("observed"),
                        "metrics": [{k: m[k] for k in ("code", "label", "value")} for m in plan.get("metrics", [])
                                    if m["code"] in ("fh", "sd")]}
        tok = snap["tokens"].get(p["id"], {}).get("windows", {})
        item["today"] = tok.get("today", {"tokens": 0, "cost": 0})
        item["running"] = {k: len(v) for k, v in procs.get(p["id"], {}).items()}
        item["account"] = cli_account(p)
        item["paths"] = {k: (str(v) if v else None) for k, v in pa.items() if k != "cli_json"}
        item["initialised"] = {k: bool(v and Path(v).exists()) for k, v in pa.items() if k != "cli_json"}
        out.append(item)
    return {"profiles": out, "settings": s, "aliases_file": str(ALIASES), "dry_run": DRY_RUN,
            "indexed": snap["ready"], "best": snap["best"]}


class Watcher:
    """Background loop: re-indexes transcripts, works out which sessions are live,
    reads plan usage, and fires notifications."""

    def __init__(self):
        self.index = monitor.SessionIndex(lambda: registry()["profiles"], paths)
        self.notifier = monitor.Notifier(settings, DRY_RUN, log, HOME / "alerts.json")
        self.runner = monitor.Runner(HOME, DRY_RUN, log, self.notifier)
        self.data = {"sessions": [], "plan": {}, "tokens": {}, "best": None, "ready": False}
        self.lock = threading.Lock()
        self.last_plan = 0

    def snapshot(self):
        with self.lock:
            return dict(self.data)

    def tick(self):
        HOME.mkdir(parents=True, exist_ok=True)
        self.index.scan()
        profs = registry()["profiles"]
        procs = classify(ps_lines(), settings())
        cli_pids = [pid for v in procs.values() for pid in v["cli"]]
        cwds = monitor.process_cwds(cli_pids)
        live = {pid: {cwds[x] for x in v["cli"] if x in cwds} for pid, v in procs.items()}
        sessions = self.index.sessions(live)
        names = {p["id"]: p["name"] for p in profs}
        self.notifier.sessions(sessions, names)
        plan = self.data["plan"]
        if time.time() - self.last_plan > 30:
            self.last_plan = time.time()
            plan = {}
            for p in profs:
                plan[p["id"]] = monitor.plan_usage(paths(p)["desktop"])
                self.notifier.usage(p["id"], p["name"], plan[p["id"]])
        tokens = self.index.usage()
        # Steering: the account with the most headroom on its tightest 5-hour/weekly limit.
        cands = [(100 - v["binding"]["value"], pid) for pid, v in plan.items()
                 if v.get("available") and v.get("binding") and not v.get("stale")]
        best = None
        if len(cands) >= 2:
            head, pid = max(cands)
            best = {"profile": pid, "headroom": round(head, 1)}
        with self.lock:
            self.data = {"sessions": sessions, "plan": plan, "tokens": tokens, "best": best, "ready": True}

    def loop(self):
        while True:
            try:
                self.tick()
            except Exception as e:
                log("WATCH ERROR %r" % e)
            time.sleep(3)


WATCH = Watcher()


class Handler(BaseHTTPRequestHandler):
    server_version = "ClaudeManager/1.0"

    def log_message(self, *a):
        pass

    def send(self, code, body, ctype="application/json"):
        if not isinstance(body, (bytes, bytearray)):
            body = json.dumps(body).encode()
        self.send_response(code)
        self.send_header("Content-Type", ctype)
        self.send_header("Cache-Control", "no-store")
        self.send_header("Content-Length", str(len(body)))
        self.end_headers()
        self.wfile.write(body)

    def authorised(self):
        host = (self.headers.get("Host") or "").split(":")[0]
        return host in ("127.0.0.1", "localhost") and self.headers.get("X-Token") == TOKEN

    def body(self):
        n = int(self.headers.get("Content-Length") or 0)
        if not n:
            return {}
        try:
            return json.loads(self.rfile.read(n))
        except ValueError:
            return {}

    def do_GET(self):
        if self.path in ("/", "/index.html"):
            html = (HERE / "index.html").read_text().replace("__TOKEN__", TOKEN)
            return self.send(200, html.encode(), "text/html; charset=utf-8")
        if not self.path.startswith("/api/"):
            return self.send(404, {"error": "not found"})
        if not self.authorised():
            return self.send(403, {"error": "forbidden"})
        url = urlparse(self.path)
        q = {k: v[0] for k, v in parse_qs(url.query).items()}
        parts = [x for x in url.path.split("/") if x]
        try:
            if parts == ["api", "state"]:
                return self.send(200, state())
            if parts == ["api", "sessions"]:
                snap = WATCH.snapshot()
                rows = snap["sessions"]
                if q.get("profile"):
                    rows = [r for r in rows if r["profile"] == q["profile"]]
                return self.send(200, {"sessions": rows[:int(q.get("limit", 300))], "ready": snap["ready"]})
            if len(parts) == 4 and parts[:2] == ["api", "sessions"]:
                fp, fs = WATCH.index.find(parts[2], parts[3])
                if not fp:
                    return self.send(404, {"error": "session not found"})
                return self.send(200, {"messages": monitor.transcript(fp), "cwd": fs.cwd, "title": fs.title or fs.first_prompt})
            if parts == ["api", "usage"]:
                snap = WATCH.snapshot()
                return self.send(200, {"plan": snap["plan"], "tokens": snap["tokens"], "best": snap["best"]})
            if parts == ["api", "runs"]:
                return self.send(200, {"runs": WATCH.runner.list()})
            if len(parts) == 3 and parts[:2] == ["api", "runs"]:
                r = WATCH.runner.get(parts[2])
                return self.send(200, r) if r else self.send(404, {"error": "no such run"})
            if parts == ["api", "notifications"]:
                return self.send(200, {"items": WATCH.notifier.recent[::-1]})
            if parts == ["api", "projects"]:
                seen, out = set(), []
                for srow in WATCH.snapshot()["sessions"]:
                    if srow["cwd"] and srow["cwd"] not in seen:
                        seen.add(srow["cwd"])
                        out.append(srow["cwd"])
                return self.send(200, {"projects": out[:30]})
        except Exception as e:
            log("ERROR %r" % e)
            return self.send(500, {"error": str(e)})
        self.send(404, {"error": "not found"})

    def do_POST(self):
        if not self.authorised():
            return self.send(403, {"error": "forbidden"})
        b = self.body()
        parts = [x for x in self.path.split("/") if x]
        try:
            if parts == ["api", "profiles"]:
                return self.send(200, self.create(b))
            if len(parts) == 4 and parts[:2] == ["api", "profiles"]:
                p = find(parts[2])
                if not p:
                    return self.send(404, {"error": "no such profile"})
                action = parts[3]
                if action in ("desktop", "cli", "browser"):
                    # Never start a second desktop/browser copy on the same data folder.
                    if action != "cli" and classify(ps_lines(), settings())[p["id"]][action]:
                        return self.send(200, {"ok": True, "already": True})
                    launch(p, action, b.get("workdir"))
                    return self.send(200, {"ok": True})
                if action == "resume":
                    fp, fs = WATCH.index.find(p["id"], b.get("session_id", ""))
                    if not fp:
                        return self.send(404, {"error": "session not found"})
                    launch(p, "cli", fs.cwd, ["--resume", fs.sid or Path(fp).stem])
                    return self.send(200, {"ok": True})
                if action == "stop":
                    kind = b.get("kind")
                    if kind not in ("desktop", "browser"):
                        return self.send(400, {"error": "can only stop desktop or browser"})
                    return self.send(200, {"stopped": stop(p, kind)})
                if action == "update":
                    return self.send(200, self.update(p, b))
                if action == "remove":
                    return self.send(200, self.remove(p))
                if action == "reveal":
                    target = paths(p)[b.get("kind", "cli")] or Path.home()
                    Path(target).mkdir(parents=True, exist_ok=True)
                    run(["open", str(target)])
                    return self.send(200, {"ok": True})
                if action == "size":
                    pa = paths(p)
                    return self.send(200, {k: folder_size(pa[k]) for k in ("desktop", "cli", "browser")})
            if parts == ["api", "runs"]:
                p = find(b.get("profile", ""))
                if not p:
                    return self.send(404, {"error": "Pick an account"})
                cfg = None if p.get("builtin") else str(paths(p)["cli"])
                if cfg:
                    Path(cfg).mkdir(parents=True, exist_ok=True)
                r = WATCH.runner.start(p["id"], p["name"], resolve_cli(), cfg, b.get("cwd") or p.get("workdir"),
                                       b.get("prompt", ""), b.get("mode", "plan"))
                touch(p)
                return self.send(200, r)
            if len(parts) == 4 and parts[:2] == ["api", "runs"] and parts[3] == "stop":
                return self.send(200, {"stopped": WATCH.runner.stop(parts[2])})
            if len(parts) == 4 and parts[:2] == ["api", "runs"] and parts[3] == "terminal":
                r = WATCH.runner.get(parts[2])
                p = r and find(r["profile"])
                if not p or not r.get("session_id"):
                    return self.send(400, {"error": "This task has no session to continue yet"})
                launch(p, "cli", r["cwd"], ["--resume", r["session_id"]])
                return self.send(200, {"ok": True})
            if parts == ["api", "settings"]:
                with LOCK:
                    s = settings()
                    for k, default in DEFAULT_SETTINGS.items():
                        v = b.get(k)
                        if isinstance(default, bool) and isinstance(v, bool):
                            s[k] = v
                        elif isinstance(default, list) and isinstance(v, list):
                            s[k] = [int(x) for x in v if str(x).isdigit() and 0 < int(x) <= 100][:4]
                        elif isinstance(default, str) and isinstance(v, str) and v.strip():
                            s[k] = v.strip()
                    save_json(SETTINGS, s)
                return self.send(200, s)
            if parts == ["api", "launch-all"]:
                kind = b.get("kind", "desktop")
                ids = b.get("ids") or []
                for pid in ids:
                    p = find(pid)
                    if p:
                        launch(p, kind)
                        time.sleep(0.4)
                return self.send(200, {"ok": True})
        except Exception as e:  # surface errors to the UI instead of crashing
            log("ERROR %r" % e)
            return self.send(500, {"error": str(e)})
        self.send(404, {"error": "not found"})

    # ---- profile CRUD
    def create(self, b):
        name = (b.get("name") or "").strip()[:40]
        if not name:
            raise ValueError("Name is required")
        with LOCK:
            data = registry()
            base = slug(name)
            pid, n = base, 2
            ids = {p["id"] for p in data["profiles"]}
            while pid in ids:
                pid, n = "%s-%d" % (base, n), n + 1
            p = {
                "id": pid, "name": name, "note": (b.get("note") or "").strip()[:80],
                "color": b.get("color") or COLORS[len(data["profiles"]) % len(COLORS)],
                "workdir": (b.get("workdir") or "~").strip(),
                "builtin": False, "created": time.time(), "last_used": None,
            }
            data["profiles"].append(p)
            save_json(REGISTRY, data)
        for d in ("desktop", "cli", "browser"):
            paths(p)[d].mkdir(parents=True, exist_ok=True)
        write_aliases()
        return p

    def update(self, p, b):
        with LOCK:
            data = registry()
            for q in data["profiles"]:
                if q["id"] == p["id"]:
                    for k, lim in (("name", 40), ("note", 80), ("color", 16), ("workdir", 400)):
                        if isinstance(b.get(k), str):
                            q[k] = b[k].strip()[:lim] or q[k]
                    if "pinned" in b:
                        q["pinned"] = bool(b["pinned"])
                    p = q
            save_json(REGISTRY, data)
        return p

    def remove(self, p):
        """Removes the profile from the dashboard. Data folders are moved to an
        archive (never deleted), so a sign-in can be recovered."""
        if p.get("builtin"):
            raise ValueError("The default profile can't be removed")
        with LOCK:
            data = registry()
            data["profiles"] = [q for q in data["profiles"] if q["id"] != p["id"]]
            save_json(REGISTRY, data)
        src = PROFILES_DIR / p["id"]
        if src.exists():
            dest = HOME / "archive" / ("%s-%d" % (p["id"], int(time.time())))
            dest.parent.mkdir(parents=True, exist_ok=True)
            shutil.move(str(src), str(dest))
        write_aliases()
        return {"ok": True}


def main():
    registry()
    write_aliases()
    try:
        srv = ThreadingHTTPServer(("127.0.0.1", PORT), Handler)
    except OSError:
        # Already running: just open the existing dashboard.
        print("Manager already running on port %d — opening it." % PORT)
        webbrowser.open("http://127.0.0.1:%d" % PORT)
        return
    threading.Thread(target=WATCH.loop, daemon=True).start()
    url = "http://127.0.0.1:%d" % PORT
    print("Claude Account Manager running at %s  (Ctrl+C to quit)" % url)
    if "--no-open" not in sys.argv:
        threading.Timer(0.6, lambda: webbrowser.open(url)).start()
    try:
        srv.serve_forever()
    except KeyboardInterrupt:
        pass


if __name__ == "__main__":
    main()
