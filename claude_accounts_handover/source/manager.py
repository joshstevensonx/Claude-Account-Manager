# ---------------------------------------------------------------- storage
def log(msg):
    HOME.mkdir(parents=True, exist_ok=True)
    with open(LOG, "a") as f:
        f.write(time.strftime("%Y-%m-%d %H:%M:%S ") + msg + "\n")


def load_json(path, default):
    try:
        with open(path) as f:
            return json.load(f)
    except (OSError, ValueError):
        return default


def save_json(path, data):
    HOME.mkdir(parents=True, exist_ok=True)
    tmp = path.with_suffix(".tmp")
    with open(tmp, "w") as f:
        json.dump(data, f, indent=2)
    os.replace(tmp, path)


def settings():
    s = dict(DEFAULT_SETTINGS)
    s.update(load_json(SETTINGS, {}))
    return s


def registry():
    data = load_json(REGISTRY, None)
    if data is None:
        data = {"profiles": [{
            "id": "default", "name": "Default", "note": "Your normal Claude install",
            "color": COLORS[0], "workdir": str(Path.home()), "builtin": True,
            "created": time.time(), "last_used": None,
        }]}
        save_json(REGISTRY, data)
    return data


def find(pid):
    for p in registry()["profiles"]:
        if p["id"] == pid:
            return p
