def slug(name):
    s = re.sub(r"[^a-z0-9]+", "-", name.lower()).strip("-")[:32]
    return s or "profile"


def paths(p):
    """Data folders for a profile. The built-in default uses the normal locations."""
    if p.get("builtin"):
        return {
            "desktop": Path.home() / "Library/Application Support/Claude",
            "cli": Path.home() / ".claude",
            "cli_json": Path.home() / ".claude.json",
            "browser": None,
        }
    base = PROFILES_DIR / p["id"]
    return {
        "desktop": base / "desktop",
        "cli": base / "cli",
        "cli_json": base / "cli" / ".claude.json",
        "browser": base / "browser",
    }


def write_aliases():
    lines = ["# Generated by Claude Account Manager — `source` this from ~/.zshrc", ""]
    for p in registry()["profiles"]:
        if p.get("builtin"):
            continue
        cfg = str(paths(p)["cli"]).replace('"', '\\"').replace("'", "")
        lines.append("alias claude-%s='CLAUDE_CONFIG_DIR=\"%s\" claude'" % (p["id"], cfg))
    HOME.mkdir(parents=True, exist_ok=True)
    ALIASES.write_text("\n".join(lines) + "\n")


# ---------------------------------------------------------------- activity log
# Launches, stops and configuration changes only. Never prompts, chat content or environment values.
ALOCK = threading.Lock()


def activity(kind, message, severity="info", profile=None, **meta):
    if not settings().get("store_activity", True):
        return
    e = {"t": time.time(), "type": kind, "severity": severity, "message": message, "profile": profile}
    if meta:
        e["meta"] = meta
    with ALOCK:
        HOME.mkdir(parents=True, exist_ok=True)
        with open(ACTIVITY, "a") as f:
            f.write(json.dumps(e) + "\n")


def read_activity(limit=500):
    cutoff = time.time() - int(settings().get("activity_days", 30)) * 86400
    out = []
    with ALOCK:
        try:
            with open(ACTIVITY) as f:
                for line in f:
                    try:
                        e = json.loads(line)
                    except ValueError:
                        continue
                    if e.get("t", 0) >= cutoff:
                        out.append(e)
        except OSError:
            pass
    return out[::-1][:limit]


def prune_activity():
    keep = read_activity(100000)[::-1]
    with ALOCK:
        if ACTIVITY.exists():
            tmp = ACTIVITY.with_suffix(".tmp")
            tmp.write_text("".join(json.dumps(e) + "\n" for e in keep))
            os.replace(tmp, ACTIVITY)


